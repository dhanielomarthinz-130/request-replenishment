<?php
/**
 * Database Connection & Migration Handler
 * Supports MySQL PDO with automatic SQLite fallback for zero-friction setup.
 */

// Set Indonesian Western Time (WIB / Asia/Jakarta, UTC+7) globally
if (function_exists('date_default_timezone_set')) {
    date_default_timezone_set('Asia/Jakarta');
}

class Database {
    private static ?PDO $pdo = null;
    private static string $driverType = 'mysql';
    private static bool $isMigrated = false;

    public static function getConnection(): PDO {
        if (self::$pdo !== null) {
            try {
                self::$pdo->query("SELECT 1");
                return self::$pdo;
            } catch (Throwable $e) {
                self::$pdo = null;
            }
        }

        // Load production config if present (e.g. generated by GitHub Actions or placed on server)
        if (file_exists(__DIR__ . '/config.php')) {
            require_once __DIR__ . '/config.php';
        }

        $host     = defined('DB_HOST') ? DB_HOST : (getenv('DB_HOST') ?: '127.0.0.1');
        $port     = defined('DB_PORT') ? DB_PORT : (getenv('DB_PORT') ?: '3306');
        $dbName   = defined('DB_NAME') ? DB_NAME : (getenv('DB_NAME') ?: 'ocs_inventory');
        $username = defined('DB_USER') ? DB_USER : (getenv('DB_USER') ?: 'root');
        $password = defined('DB_PASS') ? DB_PASS : (getenv('DB_PASS') ?: '');

        // Try MySQL First
        try {
            // 1. First try direct connection to target DB (works on InfinityFree / shared hosting where CREATE DATABASE is restricted)
            self::$pdo = new PDO("mysql:host=$host;port=$port;dbname=$dbName;charset=utf8mb4", $username, $password, [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                PDO::ATTR_TIMEOUT => 5
            ]);
            try { self::$pdo->exec("SET time_zone = '+07:00';"); } catch (Throwable $tzE) {}
            self::$driverType = 'mysql';
        } catch (Exception $eDirect) {
            // 2. If DB does not exist (e.g. fresh local XAMPP setup), try creating it
            try {
                $initPdo = new PDO("mysql:host=$host;port=$port", $username, $password, [
                    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                    PDO::ATTR_TIMEOUT => 3
                ]);
                $initPdo->exec("CREATE DATABASE IF NOT EXISTS `$dbName` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;");
                
                self::$pdo = new PDO("mysql:host=$host;port=$port;dbname=$dbName;charset=utf8mb4", $username, $password, [
                    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                    PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC
                ]);
                try { self::$pdo->exec("SET time_zone = '+07:00';"); } catch (Throwable $tzE) {}
                self::$driverType = 'mysql';
            } catch (Exception $eInit) {
                // 3. Fallback to SQLite if MySQL is offline
                $sqlitePath = __DIR__ . '/ocs_inventory.sqlite';
                self::$pdo = new PDO("sqlite:" . $sqlitePath, null, null, [
                    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                    PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC
                ]);
                self::$driverType = 'sqlite';
            }
        }

        if (!self::$isMigrated) {
            self::migrateTables();
            self::$isMigrated = true;
        }
        return self::$pdo;
    }

    public static function getDriverType(): string {
        return self::$driverType;
    }

    private static function migrateTables(): void {
        $pdo = self::$pdo;

        $schemaVersion = '20260910_v2';
        try {
            $check = $pdo->prepare("SELECT key_value FROM system_settings WHERE key_name = 'db_schema_version'");
            $check->execute();
            if ($check->fetchColumn() === $schemaVersion) {
                return;
            }
        } catch (Throwable $e) {
            // First run or system_settings table not created yet
        }

        if (self::$driverType === 'mysql') {
            // Table: users
            $pdo->exec("CREATE TABLE IF NOT EXISTS `users` (
                `id` INT AUTO_INCREMENT PRIMARY KEY,
                `username` VARCHAR(50) NOT NULL UNIQUE,
                `password` VARCHAR(255) NOT NULL,
                `full_name` VARCHAR(100) NOT NULL,
                `role` VARCHAR(50) NOT NULL DEFAULT 'operator',
                `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;");

            // Table: sku_rack_locations (Mapping Bin Code -> SKU)
            $pdo->exec("CREATE TABLE IF NOT EXISTS `sku_rack_locations` (
                `id` INT AUTO_INCREMENT PRIMARY KEY,
                `bin_code` VARCHAR(50) NOT NULL,
                `rack_name` VARCHAR(50) NOT NULL,
                `sku` VARCHAR(100) NOT NULL,
                `barcode` VARCHAR(100) DEFAULT NULL,
                `product_name` VARCHAR(255) NOT NULL,
                `category` VARCHAR(100) DEFAULT NULL,
                `notes` TEXT DEFAULT NULL,
