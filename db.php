                id INTEGER PRIMARY KEY AUTOINCREMENT,
                request_no TEXT NOT NULL UNIQUE,
                bin_code TEXT NOT NULL,
                sku TEXT NOT NULL,
                product_name TEXT NOT NULL,
                barcode TEXT,
                qty_gudang_kecil INTEGER DEFAULT 0,
