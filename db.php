    }

    /**
     * Otomatis sinkronisasi master stock dan rack mapping dari ocs_inventory.sqlite
     * ke MySQL di InfinityFree setiap kali ada update file sqlite yang di-push.
     */
    private static function syncSqliteToMysql(): void
    {
        $sqlitePath = __DIR__ . '/ocs_inventory.sqlite';
        if (!file_exists($sqlitePath)) {
            return;
        }

        $sqliteMtime = (string)filemtime($sqlitePath);
        $pdo = self::$pdo;

        // Cek apakah database MySQL sudah sinkron dengan versi file sqlite ini
        try {
            $checkStmt = $pdo->prepare("SELECT key_value FROM system_settings WHERE key_name = 'last_sqlite_sync'");
            $checkStmt->execute();
            $lastSync = $checkStmt->fetchColumn();

            $countStock = (int)$pdo->query("SELECT COUNT(*) FROM stock_master")->fetchColumn();

            // Jika mtime sama dan data stock sudah ada di MySQL, tidak perlu sync ulang
            if ($lastSync === $sqliteMtime && $countStock > 0) {
                return;
            }
        } catch (Throwable $e) {
            // Lanjut jika terjadi error pembacaan settings
        }

        try {
            if (function_exists('set_time_limit')) {
                @set_time_limit(120);
            }

            $sqlitePdo = new PDO("sqlite:" . $sqlitePath, null, null, [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC
            ]);

            $pdo->beginTransaction();

            // 1. Sync sku_rack_locations (670+ baris rak)
            $rStmt = $sqlitePdo->query("SELECT bin_code, rack_name, sku, barcode, product_name, category, notes FROM sku_rack_locations");
            $rInsert = $pdo->prepare("INSERT INTO sku_rack_locations (bin_code, rack_name, sku, barcode, product_name, category, notes) 
                VALUES (?, ?, ?, ?, ?, ?, ?) 
                ON DUPLICATE KEY UPDATE 
                    rack_name = VALUES(rack_name), 
                    barcode = VALUES(barcode), 
                    product_name = VALUES(product_name), 
                    category = VALUES(category), 
                    notes = VALUES(notes)");
            while ($row = $rStmt->fetch()) {
                $rInsert->execute([
                    $row['bin_code'], $row['rack_name'], $row['sku'], $row['barcode'], 
                    $row['product_name'], $row['category'], $row['notes']
                ]);
            }

            // 3. Sync stock_master (2500+ baris stok)
            $sStmt = $sqlitePdo->query("SELECT sku, barcode, product_name, area_id, sap_code, category, qty_on_hand, qty_available, qty_gudang_kecil, qty_gudang_besar, is_active FROM stock_master");
            $sInsert = $pdo->prepare("INSERT INTO stock_master (sku, barcode, product_name, area_id, sap_code, category, qty_on_hand, qty_available, qty_gudang_kecil, qty_gudang_besar, is_active) 
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?) 
                ON DUPLICATE KEY UPDATE 
                    barcode = VALUES(barcode), 
                    product_name = VALUES(product_name), 
                    area_id = VALUES(area_id), 
                    sap_code = VALUES(sap_code), 
                    category = VALUES(category), 
                    qty_on_hand = VALUES(qty_on_hand), 
                    qty_available = VALUES(qty_available), 
                    qty_gudang_kecil = VALUES(qty_gudang_kecil), 
                    qty_gudang_besar = VALUES(qty_gudang_besar), 
                    is_active = VALUES(is_active)");
            while ($row = $sStmt->fetch()) {
                $sInsert->execute([
                    $row['sku'], $row['barcode'], $row['product_name'], $row['area_id'], 
                    $row['sap_code'], $row['category'], $row['qty_on_hand'], $row['qty_available'], 
                    $row['qty_gudang_kecil'], $row['qty_gudang_besar'], $row['is_active']
                ]);
            }

            // 4. Update riwayat sinkronisasi
            $settStmt = $pdo->prepare("INSERT INTO system_settings (key_name, key_value) VALUES ('last_sqlite_sync', ?) 
                ON DUPLICATE KEY UPDATE key_value = VALUES(key_value)");
            $settStmt->execute([$sqliteMtime]);

            $pdo->commit();
        } catch (Throwable $e) {
            if ($pdo->inTransaction()) {
                $pdo->rollBack();
            }
            error_log("Database sync from SQLite to MySQL failed: " . $e->getMessage());
        }
    }

    /**
     * Replaces the legacy UNIQUE(bin_code) constraint on sku_rack_locations
     * with UNIQUE(bin_code, sku). Safe to run on every boot: it inspects the
     * current schema first and does nothing once the new key is in place.
     */
    private static function migrateSkuRackUniqueKey(): void
    {
        $pdo = self::$pdo;

        try {
            if (self::$driverType === 'mysql') {
                $indexes = $pdo->query("SHOW INDEX FROM `sku_rack_locations`")->fetchAll();
                $hasNewKey = false;
                $legacyKeys = [];
                foreach ($indexes as $idx) {
                    if ($idx['Key_name'] === 'uniq_bin_sku') {
                        $hasNewKey = true;
                    } elseif ((int)$idx['Non_unique'] === 0 && $idx['Key_name'] !== 'PRIMARY' && $idx['Column_name'] === 'bin_code') {
                        $legacyKeys[$idx['Key_name']] = true;
                    }
                }
                if ($hasNewKey && empty($legacyKeys)) {
                    return;
                }
                foreach (array_keys($legacyKeys) as $keyName) {
                    $pdo->exec("ALTER TABLE `sku_rack_locations` DROP INDEX `" . $keyName . "`");
                }
                if (!$hasNewKey) {
                    $pdo->exec("ALTER TABLE `sku_rack_locations` ADD UNIQUE KEY `uniq_bin_sku` (`bin_code`, `sku`)");
                }
                return;
            }

            // SQLite cannot drop a column-level UNIQUE constraint, so the table
            // has to be rebuilt and the existing rows copied across.
            $ddl = $pdo->query("SELECT sql FROM sqlite_master WHERE type = 'table' AND name = 'sku_rack_locations'")->fetch();
            $ddl = $ddl['sql'] ?? '';
            if ($ddl === '' || stripos($ddl, 'UNIQUE (bin_code, sku)') !== false) {
                return;
            }

            $pdo->exec("PRAGMA foreign_keys = OFF");
            $pdo->exec("CREATE TABLE sku_rack_locations_new (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                bin_code TEXT NOT NULL,
                rack_name TEXT NOT NULL,
                sku TEXT NOT NULL,
                barcode TEXT,
                product_name TEXT NOT NULL,
                category TEXT,
                notes TEXT,
                created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
                updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
                UNIQUE (bin_code, sku)
            )");
            $pdo->exec("INSERT INTO sku_rack_locations_new (id, bin_code, rack_name, sku, barcode, product_name, category, notes, created_at, updated_at)
                        SELECT id, bin_code, rack_name, sku, barcode, product_name, category, notes, created_at, updated_at FROM sku_rack_locations");
            $pdo->exec("DROP TABLE sku_rack_locations");
            $pdo->exec("ALTER TABLE sku_rack_locations_new RENAME TO sku_rack_locations");
            $pdo->exec("CREATE INDEX IF NOT EXISTS idx_sku_rack_sku ON sku_rack_locations (sku)");
            $pdo->exec("CREATE INDEX IF NOT EXISTS idx_sku_rack_bin ON sku_rack_locations (bin_code)");
            $pdo->exec("PRAGMA foreign_keys = ON");
        } catch (Exception $e) {
            // A failed migration must not take the whole app down; the sync
            // handler reports the duplicate-key error if this could not run.
            error_log('sku_rack_locations unique-key migration failed: ' . $e->getMessage());
        }
    }

    /**
     * Pastikan kolom rack_gudang_besar, batch_number, picked_qty, picked_by, picked_at
     * sudah tersedia di tabel replenish_requests (aman untuk MySQL dan SQLite).
     */
    private static function migrateReplenishRequestColumns(): void
    {
        $pdo = self::$pdo;
        try {
            $existingColumns = [];
            if (self::$driverType === 'mysql') {
                $stmt = $pdo->query("SHOW COLUMNS FROM `replenish_requests`");
                while ($col = $stmt->fetch()) {
                    $existingColumns[strtolower($col['Field'])] = true;
                }
            } else {
                $stmt = $pdo->query("PRAGMA table_info(replenish_requests)");
                while ($col = $stmt->fetch()) {
                    $existingColumns[strtolower($col['name'])] = true;
                }
            }

            $neededCols = [
                'rack_gudang_besar' => self::$driverType === 'mysql' ? 'VARCHAR(100) DEFAULT NULL' : 'TEXT',
                'batch_number'      => self::$driverType === 'mysql' ? 'VARCHAR(100) DEFAULT NULL' : 'TEXT',
                'picked_qty'        => self::$driverType === 'mysql' ? 'INT DEFAULT NULL' : 'INTEGER',
                'picked_by'         => self::$driverType === 'mysql' ? 'VARCHAR(100) DEFAULT NULL' : 'TEXT',
                'picked_at'         => self::$driverType === 'mysql' ? 'DATETIME DEFAULT NULL' : 'DATETIME',
                'assigned_to'       => self::$driverType === 'mysql' ? 'VARCHAR(100) DEFAULT NULL' : 'TEXT',
                'done_ocs'          => self::$driverType === 'mysql' ? 'TINYINT(1) DEFAULT 0' : 'INTEGER DEFAULT 0',
                'done_wms'          => self::$driverType === 'mysql' ? 'TINYINT(1) DEFAULT 0' : 'INTEGER DEFAULT 0',
                'done_ocs_at'       => self::$driverType === 'mysql' ? 'DATETIME DEFAULT NULL' : 'DATETIME',
                'done_wms_at'       => self::$driverType === 'mysql' ? 'DATETIME DEFAULT NULL' : 'DATETIME',
            ];

            foreach ($neededCols as $colName => $colDef) {
                if (!isset($existingColumns[$colName])) {
                    $pdo->exec("ALTER TABLE " . (self::$driverType === 'mysql' ? "`replenish_requests`" : "replenish_requests") . " ADD COLUMN {$colName} {$colDef}");
                }
            }

            // Ensure status and role are VARCHAR(50) in MySQL to support 'CANCELLED' and 'superadmin'
            if (self::$driverType === 'mysql') {
                try {
                    $pdo->exec("ALTER TABLE `users` MODIFY COLUMN `role` VARCHAR(50) NOT NULL DEFAULT 'operator'");
                } catch (Throwable $e) {}
                try {
                    $pdo->exec("ALTER TABLE `replenish_requests` MODIFY COLUMN `status` VARCHAR(50) NOT NULL DEFAULT 'PENDING'");
                } catch (Throwable $e) {}
            }
        } catch (Throwable $e) {
            error_log('migrateReplenishRequestColumns error: ' . $e->getMessage());
        }
    }

    /**
     * Seed akun bawaan untuk Administrator, Operator Gudang Kecil, dan Operator Gudang Besar
     */
    private static function seedDefaultUsers(): void
    {
        $pdo = self::$pdo;
        try {
            // Check if initial users have already been seeded.
            // If already seeded, NEVER re-insert deleted users!
