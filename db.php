                id INTEGER PRIMARY KEY AUTOINCREMENT,
                sku TEXT NOT NULL UNIQUE,
                barcode TEXT,
                product_name TEXT NOT NULL,
                area_id TEXT DEFAULT 'Pusat',
                sap_code TEXT,
                category TEXT,
