                `id` INT AUTO_INCREMENT PRIMARY KEY,
                `request_no` VARCHAR(50) NOT NULL UNIQUE,
                `bin_code` VARCHAR(50) NOT NULL,
                `sku` VARCHAR(100) NOT NULL,
                `product_name` VARCHAR(255) NOT NULL,
                `barcode` VARCHAR(100) DEFAULT NULL,
                `qty_gudang_kecil` INT DEFAULT 0,
                `qty_gudang_besar` INT DEFAULT 0,
                `qty_request` INT NOT NULL,
                `requested_by` VARCHAR(100) NOT NULL,
                `status` ENUM('PENDING', 'APPROVED', 'REJECTED', 'COMPLETED') NOT NULL DEFAULT 'PENDING',
                `admin_notes` TEXT DEFAULT NULL,
                `processed_by` VARCHAR(100) DEFAULT NULL,
                `rack_gudang_besar` VARCHAR(100) DEFAULT NULL,
                `batch_number` VARCHAR(100) DEFAULT NULL,
                `picked_qty` INT DEFAULT NULL,
                `picked_by` VARCHAR(100) DEFAULT NULL,
                `picked_at` DATETIME DEFAULT NULL,
                `assigned_to` VARCHAR(100) DEFAULT NULL,
                `done_ocs` TINYINT(1) DEFAULT 0,
                `done_wms` TINYINT(1) DEFAULT 0,
                `done_ocs_at` DATETIME DEFAULT NULL,
                `done_wms_at` DATETIME DEFAULT NULL,
                `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
                `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;");

            // Table: system_settings
            $pdo->exec("CREATE TABLE IF NOT EXISTS `system_settings` (
                `key_name` VARCHAR(50) PRIMARY KEY,
                `key_value` TEXT NOT NULL,
                `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;");

        } else {
            // SQLite Syntax
            $pdo->exec("CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                username TEXT NOT NULL UNIQUE,
                password TEXT NOT NULL,
                full_name TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'operator',
                created_at DATETIME DEFAULT CURRENT_TIMESTAMP
            );");

